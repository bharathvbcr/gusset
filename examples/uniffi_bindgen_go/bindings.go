package uniffi_bindgen_go

import (
	"context"
	"fmt"
	"time"
)

// MathOperation identifies the calculation to perform in the engine.
type MathOperation string

const (
	OpAdd      MathOperation = "Add"
	OpSubtract MathOperation = "Subtract"
	OpMultiply MathOperation = "Multiply"
	OpDivide   MathOperation = "Divide"
	OpPower    MathOperation = "Power"
	OpSqrt     MathOperation = "Sqrt"
)

// CalculateRequest holds the arguments for a mathematical calculation.
type CalculateRequest struct {
	Op MathOperation
	A  float64
	B  float64
}

// CalculateResponse represents the calculation result.
type CalculateResponse struct {
	Result          float64
	OperationsTotal int64
}

// MathErrorCode defines domain error codes returned by the Rust engine.
type MathErrorCode int32

const (
	MathErrUnknownOp      MathErrorCode = 1
	MathErrDivisionByZero MathErrorCode = 2
	MathErrNegativeRoot   MathErrorCode = 3
	MathErrOverflow       MathErrorCode = 4
)

// MathError is a typed error returned across the UniFFI boundary.
type MathError struct {
	Code    MathErrorCode
	Message string
}

func (e *MathError) Error() string {
	return fmt.Sprintf("uniffi math error [%d]: %s", e.Code, e.Message)
}

// TextTransformRequest specifies a string transformation.
type TextTransformRequest struct {
	Text        string
	ToUppercase bool
	Reverse     bool
}

// TextTransformResponse contains the transformed text.
type TextTransformResponse struct {
	Transformed string
	Length      int32
}

// SlowJobRequest specifies a duration to hold the engine worker thread.
type SlowJobRequest struct {
	DurationMillis int32
}

// SlowJobResponse reports the outcome of a slow job.
type SlowJobResponse struct {
	ElapsedMillis int64
	Status        string
}

// MathServiceClient is the typed client interface generated by uniffi-bindgen-go,
// backed by Gusset's runtime execution contract.
type MathServiceClient interface {
	Calculate(ctx context.Context, req CalculateRequest) (*CalculateResponse, error)
	TransformText(ctx context.Context, req TextTransformRequest) (*TextTransformResponse, error)
	ExecuteSlowJob(ctx context.Context, delay time.Duration) (*SlowJobResponse, error)
	TriggerPanic(ctx context.Context) error
}
