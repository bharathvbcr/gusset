//go:build ignore

// gen.go stages the archive cgo links and stamps its sha256 into
// zz_archive_hash.go.
//
// Staging. cargo leaves libgusset.a in target/release or target/debug, and it
// carries LLVM bitcode sections (a Rust staticlib bundles the prebuilt std
// rlibs, which embed theirs). Go 1.26.11 and 1.27.4 (GO-2026-6853) walk every
// local -L directory of a #cgo LDFLAGS line and refuse any library in it with
// such a section, and cargo's output directories also hold intermediate
// archives. So ffi.go links from target/gusset only, a directory this program
// owns and fills with one file: libgusset.a with those sections removed
// (internal/ltostrip). A missing step fails as "library not found", not as a
// stale or rejected archive.
//
// Hashing. The Go build cache does not hash libgusset.a, so a rebuilt archive
// with no Go change would otherwise be served from the cache, linked against
// old Rust code. The hash is of the staged file, the one the linker reads. A
// changed hash changes a source file of this package, and Go recompiles and
// relinks. The output is per machine, so it is gitignored; archive_hash.go is
// the tracked stub that says so.
//
// searched is where cargo writes the archive, release first: the archive staged
// is the one the linker picked before staging existed. gen_test.go fails if
// staged and ffi.go's -L drift apart.
package main

import (
	"bytes"
	"context"
	"crypto/sha256"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"

	"github.com/bharathvbcr/gusset/internal/ltostrip"
)

const output = "zz_archive_hash.go"

var searched = []string{
	filepath.Join("..", "..", "target", "release", "libgusset.a"),
	filepath.Join("..", "..", "target", "debug", "libgusset.a"),
}

// staged is the only archive ffi.go's -L can find.
var staged = filepath.Join("..", "..", "target", "gusset", "libgusset.a")

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "gen.go: %v\n%s was not changed.\n", err, output)
		os.Exit(1)
	}
}

func run() error {
	src, err := builtArchive()
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(staged), 0o755); err != nil {
		return fmt.Errorf("cannot create %s: %w", absolute(filepath.Dir(staged)), err)
	}
	// A failed staging must leave nothing to link, not the previous build's
	// archive: that would link old Rust code under a green generate.
	if err := os.Remove(staged); err != nil && !errors.Is(err, fs.ErrNotExist) {
		return fmt.Errorf("cannot remove the previous %s: %w", absolute(staged), err)
	}
	res, err := ltostrip.Strip(context.Background(), src, staged)
	if err != nil {
		return fmt.Errorf("staging %s: %w", absolute(src), err)
	}
	if res.Stripped > 0 {
		fmt.Printf("gen.go: staged %s: removed %v from %d of %d members with %s\n",
			absolute(staged), res.Removed, res.Stripped, res.Members, res.Tool)
	}
	data, err := os.ReadFile(staged)
	if err != nil {
		return fmt.Errorf("cannot read %s: %w", absolute(staged), err)
	}
	content := fmt.Sprintf(`// Code generated by go generate; DO NOT EDIT.

package ffi

// ArchiveHash is the sha256 of the archive cgo links:
//
//	%s
//
// staged from %s with its LTO sections removed.
// Nothing reads it. Its only job is to change when that archive does.
const ArchiveHash = %q
`, filepath.ToSlash(staged), filepath.ToSlash(src), fmt.Sprintf("%x", sha256.Sum256(data)))

	if old, err := os.ReadFile(output); err == nil && bytes.Equal(old, []byte(content)) {
		return nil
	}
	return writeAtomic(output, []byte(content))
}

// builtArchive returns the first archive cargo may have left, release before
// debug: a path that does not exist is skipped, and any other failure is an
// error rather than a reason to look further, because staging would read that
// file too.
func builtArchive() (string, error) {
	for _, p := range searched {
		info, err := os.Stat(p)
		if errors.Is(err, fs.ErrNotExist) {
			continue
		}
		if err != nil {
			return "", fmt.Errorf("cannot read %s: %w", absolute(p), err)
		}
		if info.Size() == 0 {
			return "", fmt.Errorf("%s is empty", absolute(p))
		}
		return p, nil
	}
	var msg bytes.Buffer
	msg.WriteString("no libgusset.a where cargo writes it; searched:")
	for _, p := range searched {
		fmt.Fprintf(&msg, "\n  %s", absolute(p))
	}
	msg.WriteString("\nrun `cargo build --locked --release` from the repository root first")
	if dir := os.Getenv("CARGO_TARGET_DIR"); dir != "" {
		fmt.Fprintf(&msg, "\nCARGO_TARGET_DIR=%s: cargo writes there, and cgo does not link from it", dir)
	}
	return "", errors.New(msg.String())
}

func absolute(p string) string {
	if a, err := filepath.Abs(p); err == nil {
		return a
	}
	return p
}

// writeAtomic replaces name in one rename, so a failed or interrupted write
// leaves the previous file whole. The temporary name starts with a dot, which
// the go command ignores, so a concurrent build never compiles it.
func writeAtomic(name string, data []byte) error {
	tmp, err := os.CreateTemp(".", "."+name+".*")
	if err != nil {
		return fmt.Errorf("cannot create a temporary file for %s: %w", name, err)
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return fmt.Errorf("cannot write %s: %w", tmp.Name(), err)
	}
	if err := tmp.Chmod(0o644); err != nil {
		tmp.Close()
		return fmt.Errorf("cannot chmod %s: %w", tmp.Name(), err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("cannot close %s: %w", tmp.Name(), err)
	}
	if err := os.Rename(tmp.Name(), name); err != nil {
		return fmt.Errorf("cannot replace %s: %w", name, err)
	}
	return nil
}
