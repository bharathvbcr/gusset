//go:build ignore

// gen.go stamps the sha256 of the archive cgo links into zz_archive_hash.go.
//
// The Go build cache does not hash libgusset.a, so a rebuilt archive with no Go
// change would otherwise be served from the cache, linked against old Rust
// code. A changed hash changes a source file of this package, and Go recompiles
// and relinks. The output is per machine, so it is gitignored; archive_hash.go
// is the tracked stub that says so.
//
// The paths below are the default `#cgo !gusset_pkgconfig LDFLAGS` -L
// directories in ffi.go, in the same order, so the archive hashed is the one
// the linker picks. gen_test.go fails if the two lists drift apart.
package main

import (
	"bytes"
	"crypto/sha256"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
)

const output = "zz_archive_hash.go"

var searched = []string{
	filepath.Join("..", "..", "target", "release", "libgusset.a"),
	filepath.Join("..", "..", "target", "debug", "libgusset.a"),
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "gen.go: %v\n%s was not changed.\n", err, output)
		os.Exit(1)
	}
}

func run() error {
	path, data, err := linkedArchive()
	if err != nil {
		return err
	}
	content := fmt.Sprintf(`// Code generated by go generate; DO NOT EDIT.

package ffi

// ArchiveHash is the sha256 of the archive cgo links:
//
//	%s
//
// Nothing reads it. Its only job is to change when that archive does.
const ArchiveHash = %q
`, filepath.ToSlash(path), fmt.Sprintf("%x", sha256.Sum256(data)))

	if old, err := os.ReadFile(output); err == nil && bytes.Equal(old, []byte(content)) {
		return nil
	}
	return writeAtomic(output, []byte(content))
}

// linkedArchive returns the first archive on the linker's search path, as the
// linker would choose it: a path that does not exist is skipped, and any other
// failure is an error rather than a reason to look further, because the linker
// would stop at that file too.
func linkedArchive() (string, []byte, error) {
	for _, p := range searched {
		data, err := os.ReadFile(p)
		if errors.Is(err, fs.ErrNotExist) {
			continue
		}
		if err != nil {
			return "", nil, fmt.Errorf("cannot read %s: %w", absolute(p), err)
		}
		if len(data) == 0 {
			return "", nil, fmt.Errorf("%s is empty", absolute(p))
		}
		return p, data, nil
	}
	var msg bytes.Buffer
	msg.WriteString("no libgusset.a on the path cgo links from; searched:")
	for _, p := range searched {
		fmt.Fprintf(&msg, "\n  %s", absolute(p))
	}
	msg.WriteString("\nrun `cargo build --locked --release` from the repository root first")
	if dir := os.Getenv("CARGO_TARGET_DIR"); dir != "" {
		fmt.Fprintf(&msg, "\nCARGO_TARGET_DIR=%s: cargo writes there, and cgo does not link from it", dir)
	}
	return "", nil, errors.New(msg.String())
}

func absolute(p string) string {
	if a, err := filepath.Abs(p); err == nil {
		return a
	}
	return p
}

// writeAtomic replaces name in one rename, so a failed or interrupted write
// leaves the previous file whole. The temporary name starts with a dot, which
// the go command ignores, so a concurrent build never compiles it.
func writeAtomic(name string, data []byte) error {
	tmp, err := os.CreateTemp(".", "."+name+".*")
	if err != nil {
		return fmt.Errorf("cannot create a temporary file for %s: %w", name, err)
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return fmt.Errorf("cannot write %s: %w", tmp.Name(), err)
	}
	if err := tmp.Chmod(0o644); err != nil {
		tmp.Close()
		return fmt.Errorf("cannot chmod %s: %w", tmp.Name(), err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("cannot close %s: %w", tmp.Name(), err)
	}
	if err := os.Rename(tmp.Name(), name); err != nil {
		return fmt.Errorf("cannot replace %s: %w", name, err)
	}
	return nil
}
